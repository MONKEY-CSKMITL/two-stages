"""
geometry.py — ฟีเจอร์รูปทรงของกระดูกแต่ละปล้อง (ไฟล์นี้เป็น "ห้องสมุด" ไม่ได้รันเอง)

--------------------------------------------------------------------------
ทำไมต้องมีไฟล์นี้
--------------------------------------------------------------------------
เกณฑ์ Genant ที่ใช้ให้ grade ไม่ได้ดูที่ "ลวดลายในเนื้อกระดูก" แต่ดูที่ **รูปทรง**
โดยตรง — วัดสัดส่วนความสูงที่ขอบหน้า/กลาง/หลังของปล้อง แล้วเทียบกับปล้องที่ปกติ
ฉะนั้นตัวเลขรูปทรงจาก mask ของ Stage 1 จึงไม่ใช่ข้อมูลเสริมเล็กๆ น้อยๆ แต่เป็น
สัญญาณเดียวกับที่แพทย์ใช้ตัดสิน

วัดจากข้อมูลจริงทั้ง 11,768 ปล้อง (แยก "หักทุกระดับ" ออกจาก "ปกติ") ได้ AUC ของ
ฟีเจอร์เดี่ยวๆ ตัวเดียวดังนี้:

    fill (สัดส่วนพื้นที่ที่เป็นกระดูกในกรอบ) : AUC 0.741
    ar   (ความสูง / ความกว้าง)               : AUC 0.712
    w    (ความกว้างของกรอบ)                  : AUC 0.713

เทียบกับทั้งโมเดล CNN ที่ได้ AUC 0.861 — ตัวเลขตัวเดียวที่คำนวณจาก mask ได้
สัญญาณเกินครึ่งทางของโมเดลทั้งตัว และค่ามัธยฐานของ ar/fill ลดลงตาม grade แบบ
ไล่ระดับพอดี (ar: 0.755 / 0.742 / 0.693 / 0.571, fill: 0.767 / 0.746 / 0.693 / 0.564)

--------------------------------------------------------------------------
ทำไมโมเดลถึงยังไม่ได้สัญญาณนี้ ทั้งที่ "เห็นภาพอยู่แล้ว"
--------------------------------------------------------------------------
เพราะขั้นตอนเตรียมภาพลบมันทิ้งไปเกือบหมด:

  resize_mode="pad"     ย่อภาพให้พอดีกรอบ 224 -> ขนาดสัมบูรณ์หายไป (ปล้องที่ยุบ
                        จนเตี้ยกับปล้องปกติ ถูกขยายมาเต็มกรอบเท่ากัน) แต่ยังเก็บ
                        ar ไว้ได้
  resize_mode="stretch" ยืดเป็นจัตุรัส -> ar กลายเป็น 1.0 เท่ากันหมดทุกใบ สัญญาณ
                        ที่มี AUC 0.712 หายเกลี้ยง

ข้อนี้อธิบายผลการทดลองที่ 6 ในเอกสารสรุปได้พอดี: stretch ทำให้ recall ของ mild
แย่ลงทั้ง 2 variant (bbox −13.1 pp, masked −8.7 pp) ขณะที่ severe กลับดีขึ้น —
เพราะ severe ยังมีสัญญาณอื่น (เนื้อกระดูกพัง endplate แตก) ให้จับ แต่ mild
แทบไม่มีอะไรนอกจากรูปทรงที่เปลี่ยนไปเล็กน้อย

การป้อนตัวเลขเหล่านี้เข้าโมเดลตรงๆ จึงเป็นการคืนสัญญาณที่ pipeline ทำหล่นไป
และมันรอดจากทุก resize_mode เพราะไม่ได้เดินผ่านเส้นทางภาพเลย

--------------------------------------------------------------------------
ต่างจาก metadata (การทดลองที่ 4) ตรงไหน
--------------------------------------------------------------------------
metadata (อายุ เพศ น้ำหนัก ส่วนสูง) เป็นข้อมูล **ระดับผู้ป่วย** ปล้องทั้ง 15 ปล้อง
ของคนเดียวกันได้ค่าเหมือนกันหมด จึงบอกได้แค่ "คนนี้เสี่ยงแค่ไหน" แต่บอกไม่ได้ว่า
"ปล้องไหนหัก" — ซึ่งเป็นคำอธิบายที่เอกสารสรุปให้ไว้ว่าทำไม metadata ถึงช่วย severe
แต่ทำให้ mild แย่ลง

geometry เป็นข้อมูล **ระดับปล้อง** ทุกปล้องมีค่าของตัวเอง จึงตอบคำถามที่ metadata
ตอบไม่ได้โดยตรง เป็นคนละชนิดของข้อมูลกัน เปิดใช้พร้อมกันได้และควรทดลองแยกกัน

--------------------------------------------------------------------------
ที่มาของตัวเลข และเรื่องการรั่วไหลของข้อมูล
--------------------------------------------------------------------------
ทุกค่าอ่านจาก data/interim/crops/manifest.csv ที่ crop.py เขียนไว้ตอนตัดภาพ
(คอลัมน์ x0,y0,x1,y1,w,h,pixels) — ไม่ได้คำนวณใหม่ ไม่ต้อง re-crop

ฟีเจอร์กลุ่ม "_rel" เทียบกับค่ามัธยฐานของปล้องอื่น ๆ ในตัวคนไข้เอง ซึ่ง**ไม่ใช่
การรั่วไหล** ด้วย 2 เหตุผล: (1) ใช้แต่ตัวเลขรูปทรง ไม่แตะ label เลย และ (2) การ
แบ่ง train/val/test ทำที่ระดับผู้ป่วย ปล้องทั้ง 15 ของคนเดียวกันอยู่ชุดเดียวกัน
เสมอ จึงไม่มีทางที่ค่าจากชุด test จะไหลเข้าชุด train ได้

ส่วนค่า mean/std ที่ใช้ปรับสเกล คำนวณจาก **ชุด train เท่านั้น** เหมือนที่ metadata
ทำ (ดู compute_geometry_stats)
"""

import numpy as np
import pandas as pd


# ลำดับของฟีเจอร์ในเวกเตอร์ที่ป้อนโมเดล — ห้ามสลับลำดับหลังเทรนโมเดลไปแล้ว
# (โมเดลจำว่าช่องที่ 0 คือ ar ถ้าสลับทีหลัง weight ที่เทรนไว้จะใช้ไม่ได้)
GEOMETRY_COLS = [
    "ar",        # ความสูง/ความกว้าง — ปล้องที่ยุบจะแบนลง ค่านี้ลดลง (AUC 0.712)
    "fill",      # พื้นที่กระดูก/พื้นที่กรอบ — ปล้องที่เว้าจะกินพื้นที่กรอบน้อยลง (AUC 0.741)
    "log_area",  # log ของจำนวนพิกเซลกระดูก — ขนาดสัมบูรณ์ ซึ่ง resize ลบทิ้งไป
    "h_rel",     # ความสูง เทียบกับปล้องอื่นของคนไข้คนเดียวกัน (หลักการ Genant ตรงตัว)
    "w_rel",     # ความกว้าง เทียบกับตัวเอง — ชดเชยขนาดตัวคนไข้ที่ต่างกัน
    "ar_rel",    # ar เทียบกับตัวเอง — "ปล้องนี้แบนกว่าปล้องอื่นของคนนี้ไหม"
]

NUM_GEOMETRY = len(GEOMETRY_COLS)

# ใช้ log ของจำนวนพิกเซลแทนจำนวนดิบ เพราะพื้นที่กระจายแบบเบ้ขวา (ค่าน้อยกระจุก
# ค่ามากลากยาว) การ log ทำให้ใกล้เคียงการแจกแจงปกติ ซึ่งเข้ากับการทำ z-score ทีหลัง

# --- ช่วงค่าที่เป็นไปได้ของค่าดิบจาก manifest ---
# ค่านอกช่วงเหล่านี้แปลว่า mask ของปล้องนั้นเสีย (เช่นพบ 1 ปล้องที่ h = 1431 px
# ทั้งที่ 99% ของข้อมูลอยู่ที่ 148 px — mask รั่วลงไปทั้งแถบกระดูกสันหลัง)
# ตัวเลขขอบเขตมาจาก percentile ที่วัดได้จริง แล้วเผื่อไว้กว้างๆ อีกเท่าตัว:
#   w: p1-p99 = 85-181 px (สูงสุด 223)   h: p1-p99 = 60-148 px
GEOMETRY_RAW_RANGE = {
    "w": (20, 400),
    "h": (20, 400),
    "pixels": (100, 200_000),
}

# --- ช่วงค่าที่เป็นไปได้ของค่าที่คำนวณต่อ ---
# เช็คซ้ำอีกชั้นเพราะ w กับ h อาจอยู่ในช่วงปกติทั้งคู่ แต่พอหารกันแล้วได้ค่าประหลาด
#   ar:   p1-p99 = 0.52-1.03 (กระดูกสันหลังกว้างกว่าสูงเสมอในภาพด้านข้าง)
#   fill: ต้องอยู่ใน (0, 1] เสมอตามนิยาม
GEOMETRY_DERIVED_RANGE = {
    "ar": (0.15, 3.0),
    "fill": (0.05, 1.0),
}


def _invalidate_out_of_range(df: pd.DataFrame, ranges: dict, stage: str) -> None:
    """
    เปลี่ยนค่าที่อยู่นอกช่วงที่เป็นไปได้ให้เป็น NaN (แก้ตาราง df ที่ส่งเข้ามาเลย)

    ไม่ทิ้งแถวนั้น และไม่แทนค่าตรงนี้ — ปล่อยเป็น NaN ไว้ก่อน แล้วให้
    normalize_geometry_row() เติมด้วยค่ามัธยฐานของชุด train ทีหลัง
    เหตุผล: ค่ามัธยฐานต้องมาจากชุด train เท่านั้น ซึ่งตอนนี้ยังไม่รู้ว่าแถวไหน
    อยู่ชุดไหน (ไฟล์นี้อ่าน manifest ทั้งก้อนก่อนการแบ่ง split)
    """
    for col, (lo, hi) in ranges.items():
        bad = ~df[col].between(lo, hi)
        if bad.any():
            ids = df.loc[bad, "patient_id"].tolist()
            print(f"  เตือน (geometry/{stage}): {col} มีค่านอกช่วง {lo}-{hi} จำนวน {bad.sum()} ปล้อง "
                  f"(patient_id: {ids[:5]}{'...' if len(ids) > 5 else ''}) -> จะแทนด้วยค่ามัธยฐาน")
            df.loc[bad, col] = np.nan


def load_geometry(manifest_csv: str, id_width: int = 4) -> pd.DataFrame:
    """
    อ่านตัวเลขรูปทรงจาก manifest.csv ของ crop.py แล้วคำนวณฟีเจอร์ทั้ง 6 ตัว

    input:  manifest_csv = data/interim/crops/manifest.csv
                           (คอลัมน์: image, label, x0, y0, x1, y1, w, h, pixels)
            id_width     = จำนวนหลักของรหัสคนไข้ (4 = "0002") ต้องตรงกับที่
                           adapt_manifest.py ใช้ ไม่งั้น join ไม่ติดสักแถว
    output: ตาราง index = (patient_id, level_index), คอลัมน์ = GEOMETRY_COLS

    ลำดับการทำงานสำคัญ: ทำความสะอาดค่าดิบ -> คำนวณค่า derive -> ทำความสะอาดอีกรอบ
    -> คำนวณค่าเทียบกับตัวคนไข้เอง ถ้าสลับลำดับ (เช่นคำนวณ ar ก่อนล้าง h) ค่าเสีย
    1 ค่าจะลามไปทำให้ค่ามัธยฐานของคนไข้คนนั้นเพี้ยนทั้งคน
    """
    df = pd.read_csv(manifest_csv)

    # คอลัมน์ในไฟล์ชื่อ image/label — เปลี่ยนเป็นชื่อเดียวกับที่ split CSV ใช้
    # เพื่อให้ join กันได้ตรงๆ (crop.py ใช้คำว่า label หมายถึงเลขปล้องใน mask
    # ไม่ใช่ label ของโจทย์ ซึ่งชวนสับสน จึงเปลี่ยนชื่อตั้งแต่ตรงนี้)
    df["patient_id"] = df["image"].astype(int).astype(str).str.zfill(id_width)
    df["level_index"] = df["label"].astype(int)

    # ขั้นที่ 1: ล้างค่าดิบ
    _invalidate_out_of_range(df, GEOMETRY_RAW_RANGE, "ค่าดิบ")

    # ขั้นที่ 2: คำนวณฟีเจอร์ที่ไม่ต้องพึ่งปล้องอื่น
    df["ar"] = df["h"] / df["w"]
    df["fill"] = df["pixels"] / (df["w"] * df["h"])
    df["log_area"] = np.log(df["pixels"])

    # ขั้นที่ 3: ล้างค่าที่คำนวณแล้วอีกรอบ
    _invalidate_out_of_range(df, GEOMETRY_DERIVED_RANGE, "ค่าที่คำนวณ")

    # ขั้นที่ 4: เทียบกับปล้องอื่นของคนไข้คนเดียวกัน
    # transform("median") = คำนวณมัธยฐานของกลุ่ม แล้วกระจายค่ากลับไปทุกแถวในกลุ่ม
    # ใช้มัธยฐานไม่ใช่ค่าเฉลี่ย เพราะคนไข้ 1 คนมักมีปล้องหักไม่กี่ปล้องจาก 15 ปล้อง
    # มัธยฐานจึงสะท้อน "ปล้องปกติของคนนี้" ได้ดีกว่า (ตรงกับที่แพทย์ใช้เป็นตัวเทียบ)
    # pandas ข้าม NaN ให้อัตโนมัติตอนหามัธยฐาน
    for src, dst in [("h", "h_rel"), ("w", "w_rel"), ("ar", "ar_rel")]:
        patient_median = df.groupby("patient_id")[src].transform("median")
        df[dst] = df[src] / patient_median

    return df.set_index(["patient_id", "level_index"])[GEOMETRY_COLS]


def attach_geometry(df: pd.DataFrame, geometry: pd.DataFrame) -> pd.DataFrame:
    """
    เชื่อมฟีเจอร์รูปทรงเข้ากับตาราง split (join ด้วย patient_id + level_index)

    ต่างจาก attach_metadata ตรงที่ join ด้วย "คีย์คู่" ไม่ใช่ patient_id อย่างเดียว
    เพราะ geometry เป็นข้อมูลระดับปล้อง แต่ละปล้องมีค่าไม่เหมือนกัน

    ตั้งชื่อคอลัมน์ด้วยคำนำหน้า geom_ เพื่อไม่ให้ชนกับคอลัมน์เดิมของตาราง split
    และเพื่อให้แยกออกจาก meta_ ของ metadata ได้ชัดเจน
    """
    df = df.copy()

    # สร้าง index คู่ให้ตรงกับฝั่ง geometry แล้วดึงค่ามาทีละคอลัมน์
    keys = pd.MultiIndex.from_arrays([df["patient_id"], df["level_index"].astype(int)])
    for col in GEOMETRY_COLS:
        df[f"geom_{col}"] = geometry[col].reindex(keys).to_numpy()

    # แถวที่หา geometry ไม่เจอเลย = manifest กับ split ไม่ตรงกัน ซึ่งแปลว่ามีอะไร
    # ผิดตั้งแต่ต้นน้ำ (เช่นชี้ manifest ผิดไฟล์ หรือ re-crop แล้วแต่ยังใช้ split เก่า)
    # ไม่ควรปล่อยผ่านเงียบๆ ให้ค่ากลายเป็นค่ามัธยฐานทั้งชุด
    #
    # ต้องเช็คจาก "คีย์หาไม่เจอใน index" ไม่ใช่จาก "ค่าเป็น NaN" — เพราะค่าที่ถูก
    # _invalidate_out_of_range() ล้างทิ้งก็เป็น NaN เหมือนกัน แต่เป็นคนละปัญหา
    # (mask เสียเป็นจุดๆ ซึ่งจัดการได้ด้วยการเติมค่ามัธยฐาน ต่างจากชี้ไฟล์ผิดทั้งไฟล์)
    missing = int((~keys.isin(geometry.index)).sum())
    if missing:
        pct = missing / len(df) * 100
        msg = (f"เชื่อม geometry ไม่ติด {missing} จาก {len(df)} ปล้อง ({pct:.1f}%) — "
               f"เช็คว่า data.geometry_manifest ชี้ไปที่ manifest.csv ของ crop รอบเดียวกับ split หรือไม่")
        if pct > 5:
            raise ValueError(msg)   # หลุดเยอะขนาดนี้แปลว่าผิดไฟล์ ไม่ใช่ข้อมูลขาดเป็นจุดๆ
        print(f"  เตือน: {msg}")

    return df


def compute_geometry_stats(train_df: pd.DataFrame) -> dict:
    """
    คำนวณค่าสถิติสำหรับปรับสเกล geometry — ใช้ "ชุด train เท่านั้น"

    เหตุผลเดียวกับ compute_metadata_stats: ถ้าคำนวณจากข้อมูลทั้งหมด ค่าเฉลี่ยของ
    ชุด test จะแอบส่งผลต่อการเทรน ทำให้ผลที่รายงานดูดีเกินจริง

    output: dict ของแต่ละคอลัมน์ เก็บ median (ไว้เติมค่าที่ขาด), mean, std
    """
    stats = {}
    for col in GEOMETRY_COLS:
        vals = train_df[f"geom_{col}"].astype(float)
        median = float(vals.median())
        filled = vals.fillna(median)
        std = float(filled.std())
        stats[col] = {
            "median": median,
            "mean": float(filled.mean()),
            # กัน std = 0 (จะหารด้วยศูนย์) — เกิดได้ถ้าคอลัมน์นั้นมีค่าเดียวทั้งชุด
            "std": std if std > 1e-6 else 1.0,
        }
    return stats


def normalize_geometry_row(row, stats: dict) -> np.ndarray:
    """
    แปลง geometry ของ 1 แถว เป็นเวกเตอร์ตัวเลขที่ปรับสเกลแล้ว (z-score)

    คืน array ขนาด NUM_GEOMETRY เรียงตามลำดับใน GEOMETRY_COLS เสมอ
    """
    out = np.zeros(NUM_GEOMETRY, dtype=np.float32)
    for i, col in enumerate(GEOMETRY_COLS):
        v = row[f"geom_{col}"]
        s = stats[col]
        if pd.isna(v):
            v = s["median"]      # ค่าขาดหาย/ถูกตัดทิ้ง -> เติมด้วยมัธยฐานของชุด train
        out[i] = (float(v) - s["mean"]) / s["std"]
    return out
