"""
losses.py — ตัววัดว่าโมเดลทายผิดแค่ไหน (ไฟล์นี้เป็น "ห้องสมุด" ไม่ได้รันเอง)

loss คือ "ตัวเลขเดียว" ที่บอกว่าคำตอบที่โมเดลทายห่างจากคำตอบจริงแค่ไหน
ยิ่งตัวเลขนี้น้อย = ทายแม่นขึ้น การเทรนทั้งหมดคือกระบวนการค่อยๆ ปรับค่าในโมเดล
ให้ตัวเลขนี้ลดลงเรื่อยๆ

ทำไมไม่ใช้ loss มาตรฐาน (cross-entropy) เฉยๆ:
  ข้อมูลเราไม่สมดุลอย่างรุนแรง — ปล้องปกติมีถึง 92% ของทั้งหมด
  ถ้าใช้ loss ธรรมดา โมเดลจะพบว่า "ทายว่าปกติทุกครั้ง" ก็ได้คะแนนดีแล้ว (ถูก 92%)
  แล้วจะไม่ยอมเรียนรู้ที่จะจับปล้องที่หักเลย ซึ่งเป็นสิ่งที่เราต้องการจริงๆ

Focal Loss แก้ปัญหานี้ด้วย 2 กลไกซ้อนกัน:
  1. ลดน้ำหนักตัวอย่างที่ "ทายง่ายอยู่แล้ว" (ปล้องปกติชัดๆ) ให้แทบไม่มีผลต่อการเรียนรู้
  2. ถ่วงน้ำหนักคลาสที่มีตัวอย่างน้อย (รุนแรง) ให้มีความสำคัญมากขึ้น
"""

import torch
import torch.nn as nn
import torch.nn.functional as F   # F = ฟังก์ชันคณิตศาสตร์สำเร็จรูปของ PyTorch


class FocalLoss(nn.Module):
    """
    Focal Loss — loss ที่ออกแบบมาสำหรับข้อมูลไม่สมดุลโดยเฉพาะ

    ใช้ได้ทั้งโจทย์ 4 คลาสและ 2 คลาส โดยไม่ต้องแก้อะไร
    (จำนวนคลาสถูกกำหนดโดยขนาดของ logits ที่โมเดลคายมา ไม่ได้ hardcode ไว้ในนี้)
    """

    def __init__(self, alpha=None, gamma: float = 2.0):
        """
        alpha = น้ำหนักถ่วงของแต่ละคลาส (tensor ขนาดเท่าจำนวนคลาส)
                มาจาก compute_class_weights() ใน dataset.py
                ใส่ None ถ้าไม่อยากถ่วงน้ำหนักคลาส
        gamma = ตัวคุมว่าจะ "ลดความสำคัญของตัวอย่างที่ทายง่าย" แรงแค่ไหน
                gamma=0 -> ไม่ลดเลย (กลายเป็น cross-entropy ธรรมดา)
                gamma=2 -> ค่ามาตรฐานที่ใช้กันทั่วไป (ค่าที่เลือกใช้)
                ยิ่งมาก -> ยิ่งเน้นตัวอย่างที่ทายยาก
        """
        super().__init__()
        self.gamma = gamma

        # register_buffer = บอก PyTorch ว่า "เก็บ tensor นี้ไว้กับโมเดล แต่ไม่ใช่ weight ที่ต้องเรียนรู้"
        # ประโยชน์: เวลาย้ายโมเดลไป GPU (.to("cuda")) tensor นี้จะย้ายตามไปเองอัตโนมัติ
        # ถ้าเก็บเป็นตัวแปรธรรมดา จะค้างอยู่บน CPU แล้ว error ตอนคำนวณกับข้อมูลบน GPU
        if alpha is not None:
            self.register_buffer("alpha", alpha)
        else:
            self.alpha = None

    def forward(self, logits, target):
        """
        logits = คะแนนดิบที่โมเดลคายมา รูปร่าง (จำนวนตัวอย่าง, จำนวนคลาส)
        target = คำตอบจริง รูปร่าง (จำนวนตัวอย่าง,) ค่าเป็นเลขคลาส เช่น 0,1,2,3

        คืน loss เป็นตัวเลขเดียว (ค่าเฉลี่ยของทุกตัวอย่างใน batch)
        """
        # แปลงคะแนนดิบเป็น "ความน่าจะเป็นในรูป log" ของทุกคลาส
        # ใช้ log_softmax แทน softmax ธรรมดาเพราะเสถียรกว่าในการคำนวณ (ไม่เกิดเลขล้น)
        log_prob = F.log_softmax(logits, dim=-1)
        prob = log_prob.exp()   # แปลงกลับเป็นความน่าจะเป็นปกติ (0.0-1.0)

        # .gather(1, index) = ดึงค่าเฉพาะตำแหน่งที่ระบุออกมา
        # ในที่นี้คือ "ดึงความน่าจะเป็นของคลาสที่เป็นคำตอบจริง" ของแต่ละตัวอย่าง
        # target.unsqueeze(1) = เปลี่ยนรูปร่างจาก (N,) เป็น (N,1) ให้ตรงกับที่ gather ต้องการ
        # .squeeze(1) = ยุบกลับเป็น (N,) หลังดึงเสร็จ
        log_pt = log_prob.gather(1, target.unsqueeze(1)).squeeze(1)
        pt = prob.gather(1, target.unsqueeze(1)).squeeze(1)

        # pt = "โมเดลมั่นใจแค่ไหนว่าคำตอบคือคลาสที่ถูกต้อง" (0.0 = ไม่มั่นใจเลย, 1.0 = มั่นใจเต็มที่)
        #
        # หัวใจของ Focal Loss อยู่ที่ (1 - pt) ** gamma:
        #   ถ้าโมเดลทายถูกและมั่นใจสูง (pt ใกล้ 1) -> (1-pt) ใกล้ 0 -> loss เกือบเป็นศูนย์
        #      แปลว่าตัวอย่างนี้แทบไม่มีผลต่อการเรียนรู้ (ทำได้ดีอยู่แล้ว ไม่ต้องเรียนซ้ำ)
        #   ถ้าโมเดลทายพลาดหรือไม่มั่นใจ (pt ใกล้ 0) -> (1-pt) ใกล้ 1 -> loss เต็มที่
        #      แปลว่าตัวอย่างนี้มีผลเต็มๆ (นี่คือสิ่งที่โมเดลต้องเรียนรู้)
        #
        # -log_pt คือ loss แบบ cross-entropy ปกติ (ยิ่งทายผิด ยิ่งมีค่ามาก)
        focal = (1.0 - pt) ** self.gamma * (-log_pt)

        # ถ้ามีการถ่วงน้ำหนักคลาส: คูณเพิ่มตามคลาสของแต่ละตัวอย่าง
        # (คลาสที่มีตัวอย่างน้อย เช่น "รุนแรง" จะได้น้ำหนักมาก โมเดลจะใส่ใจมากขึ้น)
        if self.alpha is not None:
            at = self.alpha.gather(0, target)   # ดึงน้ำหนักของคลาสที่เป็นคำตอบจริง
            focal = at * focal

        # .mean() = เฉลี่ยทุกตัวอย่างใน batch ให้เหลือตัวเลขเดียว
        # (backprop ต้องการตัวเลขเดียวเป็นจุดเริ่มต้นเสมอ)
        return focal.mean()