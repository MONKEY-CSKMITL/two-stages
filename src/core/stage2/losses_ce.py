"""
losses_ce.py — Cross Entropy Loss ธรรมดา (ไฟล์นี้เป็น "ห้องสมุด" ไม่ได้รันเอง)

แยกออกมาจาก losses.py (ที่มี FocalLoss) ตามที่ตกลงกันไว้ — ไม่แก้ไฟล์เดิมเลย
สร้างไฟล์ใหม่แทน เพราะเหตุผลที่ต้องใช้ CE แทน Focal Loss เปลี่ยนไปจากที่คิดไว้แรก:

เดิมกลัวว่าข้อมูลไม่สมดุล (grade ปกติ 92%) เลยต้องมี Focal Loss ช่วยถ่วง
แต่พอ downsample ข้อมูล (ตัดปล้อง normal ทิ้งบางส่วนให้สัดส่วนสมดุลขึ้น) ปัญหา
ความไม่สมดุลถูกแก้ที่ "ตัวข้อมูล" ไปแล้ว — ไม่จำเป็นต้องมีกลไกพิเศษซ้อนอีกชั้นที่
"loss function" ด้วย (แก้ปัญหาเดียวกันซ้ำ 2 จุดเสี่ยง over-correct) จึงกลับมาใช้
Cross Entropy ธรรมดาได้

หน้าตา/อินเทอร์เฟซของคลาสนี้ทำให้เหมือน FocalLoss ทุกประการ (รับ/คืนค่าแบบเดียวกัน)
เพื่อให้ train.py สลับใช้ตัวไหนก็ได้โดยไม่ต้องเขียนโค้ดคนละแบบ
"""

import torch.nn as nn
import torch.nn.functional as F


class WeightedCrossEntropyLoss(nn.Module):
    """
    Cross Entropy Loss มาตรฐาน — ทุกตัวอย่างมีน้ำหนักเท่ากันหมด (ไม่มีกลไก
    "โฟกัสตัวอย่างยาก" แบบ Focal Loss และไม่มีกลไก "ถ่วงน้ำหนักคลาส" ถ้าไม่ใส่ alpha มา)

    เทียบเท่าทางคณิตศาสตร์กับ FocalLoss(gamma=0) เป๊ะ ไม่ว่าจะใส่ alpha หรือไม่ก็ตาม
    (พิสูจน์ด้วยตัวเลขจริงแล้วทั้ง 2 กรณี) เขียนแยกไฟล์นี้ไว้ให้ชื่อคลาส/เหตุผลการใช้งาน
    ชัดเจน ไม่ต้องอาศัยการตั้ง gamma=0 ผ่าน FocalLoss ซึ่งอาจทำให้งงว่าทำไมต้องอ้อมไปทางนั้น

    ทำไมไม่เรียก F.cross_entropy(weight=...) ของ PyTorch ตรงๆ (ที่ดูเหมือนจะง่ายกว่า):
    เพราะ PyTorch หารด้วย "ผลรวมน้ำหนักที่ใช้จริงใน batch" ตอนมี weight ส่วน FocalLoss
    ในโปรเจกต์นี้หารด้วย "จำนวนตัวอย่าง (N)" เฉยๆ เสมอ (ตามสูตรจากเปเปอร์ต้นฉบับของ
    Focal Loss) — 2 ธรรมเนียมนี้ต่างกันจริง (ทดสอบแล้วต่างกันได้หลายเท่าตัวเมื่อ alpha
    แต่ละคลาสห่างกันมาก) เขียนเองแบบ manual ด้านล่างเพื่อให้ตรงกับธรรมเนียมของ FocalLoss
    ที่ใช้อยู่ทั้งโปรเจกต์ ไม่ใช่ธรรมเนียมของ PyTorch เอง — เลือกทางนี้แทนที่จะไปแก้
    FocalLoss ให้ตรงกับ PyTorch เพราะการทดลองกว่า 10 รอบที่รันมาแล้วทั้งหมดใช้สูตรเดิม
    ของ FocalLoss อยู่ ถ้าแก้ย้อนหลังจะเทียบผลเก่ากับใหม่กันไม่ได้ตรงๆ อีกต่อไป
    """

    def __init__(self, alpha=None):
        """
        alpha = น้ำหนักถ่วงของแต่ละคลาส (tensor ขนาดเท่าจำนวนคลาส) — ปกติไม่ใส่
                (None) เพราะ downsampling แก้ความไม่สมดุลที่ตัวข้อมูลไปแล้ว
                เผื่อไว้เป็นทางเลือกกรณีอยากลองถ่วงคลาสเพิ่มเติมแม้ downsample แล้วก็ตาม
        """
        super().__init__()
        # register_buffer = ให้ PyTorch ย้าย tensor นี้ไป GPU ตามโมเดลอัตโนมัติ
        # (หลักการเดียวกับที่ทำใน FocalLoss)
        if alpha is not None:
            self.register_buffer("alpha", alpha)
        else:
            self.alpha = None

    def forward(self, logits, target):
        """
        logits = คะแนนดิบที่โมเดลคายมา รูปร่าง (จำนวนตัวอย่าง, จำนวนคลาส)
        target = คำตอบจริง รูปร่าง (จำนวนตัวอย่าง,) ค่าเป็นเลขคลาส เช่น 0,1,2,3

        คืน loss เป็นตัวเลขเดียว (ค่าเฉลี่ยของทุกตัวอย่างใน batch)

        ทำเองทีละขั้นตอน (ไม่เรียก F.cross_entropy ตรงๆ) เพื่อควบคุมสูตรหารตอนท้ายให้
        ตรงกับ FocalLoss เป๊ะ — เหมือนกับ FocalLoss ทุกบรรทัด แค่ไม่มีพจน์ (1-pt)^gamma
        คูณเข้าไป (เทียบเท่ากับตั้ง gamma=0 ใน FocalLoss ตลอดเวลา)
        """
        # แปลงคะแนนดิบเป็น "ความน่าจะเป็นในรูป log" (เสถียรกว่า softmax ธรรมดา)
        log_prob = F.log_softmax(logits, dim=-1)

        # ดึงเฉพาะช่องที่ตรงกับคำตอบจริงของแต่ละตัวอย่างออกมา
        log_pt = log_prob.gather(1, target.unsqueeze(1)).squeeze(1)

        loss = -log_pt   # นี่คือ cross entropy ของแต่ละตัวอย่าง (ยังไม่ถ่วงน้ำหนัก)

        # ถ้ามีการถ่วงน้ำหนักคลาส: คูณเพิ่มตามคลาสของแต่ละตัวอย่าง (เหมือน FocalLoss เป๊ะ)
        if self.alpha is not None:
            at = self.alpha.gather(0, target)
            loss = at * loss

        # .mean() = หารด้วยจำนวนตัวอย่าง (N) เสมอ ไม่ว่าจะมี alpha หรือไม่ — ตรงกับสูตร
        # ของ FocalLoss ในโปรเจกต์นี้ ไม่ใช่สูตร weighted-mean ของ PyTorch
        return loss.mean()