"""
channels.py — ประกอบ 3 ช่องสีที่ป้อนโมเดล (ไฟล์นี้เป็น "ห้องสมุด" ไม่ได้รันเอง)

--------------------------------------------------------------------------
ปัญหาที่แก้
--------------------------------------------------------------------------
backbone ที่ pretrain มาบน ImageNet ต้องการ input 3 ช่องเสมอ แต่ภาพ X-ray ของเรา
เป็นขาวดำช่องเดียว โค้ดเดิมจึง "ก๊อปช่องเดียวกัน 3 ครั้ง" ซึ่งทำให้ 2 ใน 3 ช่อง
ไม่ให้ข้อมูลอะไรใหม่เลย — เปลืองความจุของ backbone ไปฟรีๆ

--------------------------------------------------------------------------
ทำไมถึงคุ้มที่จะแก้ (มีหลักฐานจากการทดลองของเราเอง)
--------------------------------------------------------------------------
ผลชุด 15ep/patience 3 พบว่าภาพ 2 แบบเก่งคนละคลาสกันชัดเจน:

    ภาพดิบ (aug_strong)          recall mild = 0.543  moderate = 0.392
    ภาพผ่าน CLAHE (aug_strong_clahe)  recall mild = 0.478  moderate = 0.471

คือถ้าเลือกภาพดิบก็ได้ mild แต่เสีย moderate ถ้าเลือก CLAHE ก็สลับกัน — เป็น
สถานการณ์ที่ต้อง "เลือกอย่างใดอย่างหนึ่ง" ทั้งที่ไม่จำเป็น เพราะเรามีช่องว่าง
อีก 2 ช่องที่ตอนนี้ใส่ข้อมูลซ้ำอยู่

การใส่ทั้งภาพดิบและภาพ CLAHE ลงคนละช่อง เปลี่ยนคำถามจาก "อันไหนดีกว่า"
เป็น "ใช้ทั้งคู่พร้อมกัน" โดยไม่เพิ่มพารามิเตอร์ของโมเดลแม้แต่ตัวเดียว
(ชั้นแรกของ backbone รับ 3 ช่องอยู่แล้ว แค่เปลี่ยนว่าแต่ละช่องมีอะไร)

--------------------------------------------------------------------------
ช่อง mask มาจากไหน — และทำไมไม่ต้อง re-crop
--------------------------------------------------------------------------
crop.py เซฟไว้แค่ภาพ ไม่ได้เซฟ mask แยก แต่ crop แบบ xray_masked ถูกสร้างด้วย
np.where(mask, xray, 0) คือทาพื้นหลังเป็น 0 สนิท จึงกู้ mask กลับมาได้ด้วย
เงื่อนไข (img > 0) ตรงๆ

ตรวจสอบความแม่นแล้ว: ในภาพ xray_bbox (ซึ่งไม่มีการทา mask เลย) มีพิกเซลที่ค่า
เป็น 0 พอดีเพียง 0.0005% แปลว่าเนื้อกระดูกจริงแทบไม่มีทางมีค่า 0 การกู้ mask
ด้วยวิธีนี้จึงคลาดเคลื่อนในระดับที่ไม่มีนัยสำคัญ

⚠️ ใช้ได้เฉพาะ variant "xray_masked" — ถ้าใช้กับ "xray_bbox" ช่อง mask จะเป็น 1
เกือบทั้งภาพ (เพราะไม่มีพื้นหลังดำ) ซึ่งไม่ให้ข้อมูลอะไรเลย ดู build_channels()
ที่จะเตือนให้เมื่อเจอกรณีนี้

--------------------------------------------------------------------------
ข้อควรรู้เรื่องการ normalize
--------------------------------------------------------------------------
ทุกช่องถูก normalize ด้วยค่า ImageNet ชุดเดิม (คนละค่าในแต่ละช่อง) เหมือนที่
โค้ดเดิมทำทุกประการ — ตั้งใจไม่เปลี่ยน เพราะถ้าเปลี่ยนวิธี normalize ไปด้วย
จะแยกไม่ออกว่าผลที่ต่างไปมาจาก "ช่องสีใหม่" หรือ "วิธี normalize ใหม่"
(ช่อง mask ที่มีค่า 0/1 จะกลายเป็นราว -1.8 ถึง +2.6 ซึ่งอยู่ในสเกลใกล้เคียง
ช่องอื่นพอดี ไม่ต้องปรับอะไรเพิ่ม)
"""

import numpy as np
from PIL import Image

from .preprocessing import BACKGROUND_VALUE, clahe as _clahe_fn


# ============================================================================
# ตัวสร้างช่องแต่ละแบบ — ทุกตัวรับภาพ PIL คืน array (H, W) ค่า 0.0-1.0
# ============================================================================

def _ch_gray(img: Image.Image) -> np.ndarray:
    """ภาพขาวดำตามที่เป็น — ช่องพื้นฐานที่โค้ดเดิมใช้ซ้ำทั้ง 3 ช่อง"""
    return np.array(img, dtype=np.float32) / 255.0


def _ch_clahe(img: Image.Image) -> np.ndarray:
    """
    ภาพที่ผ่าน CLAHE — เน้นความเปรียบต่างเฉพาะจุด ทำให้เส้น endplate เด่นขึ้น

    ใช้ฟังก์ชันตัวเดียวกับที่ preprocessing.py ใช้ จึงได้กติกาพื้นหลัง 3 ข้อ
    (คิดสถิติจากพิกเซลกระดูก / ทาพื้นหลังกลับเป็น 0 / กระดูกไม่เป็น 0) มาฟรี
    """
    return np.array(_clahe_fn(img), dtype=np.float32) / 255.0


def _ch_mask(img: Image.Image) -> np.ndarray:
    """
    รูปทรงของปล้องล้วนๆ (1 = กระดูก, 0 = พื้นหลัง) ไม่มีข้อมูลความเข้มเลย

    ให้โมเดลเห็น "ขอบเขตของกระดูก" แบบชัดเจนโดยไม่ต้องอนุมานจากความสว่าง
    ซึ่งตรงกับสิ่งที่เกณฑ์ Genant วัด (สัดส่วนความสูงที่ขอบหน้า/กลาง/หลัง)
    """
    return (np.array(img) > BACKGROUND_VALUE).astype(np.float32)


CHANNEL_BUILDERS = {
    "gray": _ch_gray,
    "clahe": _ch_clahe,
    "mask": _ch_mask,
}


# ============================================================================
# สูตรช่องสีสำเร็จรูป — อ้างด้วยชื่อจาก config (data.channels)
# ============================================================================

CHANNEL_SPECS = {
    # เดิมทุกประการ — ก๊อปช่องเดียวกัน 3 ครั้ง (ค่าเริ่มต้น ไม่ต้องแก้ config เก่า)
    "gray3": ("gray", "gray", "gray"),

    # สูตรหลักที่ต้องการทดสอบ: ภาพดิบ + CLAHE + รูปทรง
    "gray_clahe_mask": ("gray", "clahe", "mask"),

    # แยกผลของ 2 ส่วนออกจากกัน เพื่อรู้ว่าที่ดีขึ้น (ถ้าดีขึ้น) มาจากช่องไหน
    "gray_clahe_gray": ("gray", "clahe", "gray"),   # เพิ่มแค่ CLAHE
    "gray_gray_mask": ("gray", "gray", "mask"),     # เพิ่มแค่ mask
}

MASK_CHANNEL_VARIANTS = {"xray_masked"}   # variant ที่ช่อง mask ใช้ได้จริง


def get_channel_spec(name):
    """
    แปลงชื่อสูตรจาก config เป็น tuple ของชื่อช่อง 3 ตัว

    ไม่ระบุมา (None) = "gray3" ซึ่งเป็นพฤติกรรมเดิมทุกประการ config เก่าจึงรัน
    ซ้ำได้ผลเหมือนเดิมโดยไม่ต้องแก้อะไร
    """
    if name is None:
        return CHANNEL_SPECS["gray3"]

    key = str(name).strip().lower()
    if key not in CHANNEL_SPECS:
        valid = ", ".join(sorted(CHANNEL_SPECS))
        raise ValueError(
            f"data.channels = '{name}' ไม่รู้จัก — ต้องเป็นหนึ่งใน: {valid}\n"
            f"(ถ้าเพิ่งเพิ่มสูตรใหม่ อย่าลืมลงทะเบียนใน CHANNEL_SPECS ที่ channels.py)"
        )
    return CHANNEL_SPECS[key]


def build_channels(img: Image.Image, spec) -> np.ndarray:
    """
    ประกอบภาพ 1 ใบเป็น array 3 ช่องตามสูตรที่ระบุ

    input:  img  = ภาพ PIL โหมด "L" ที่ผ่าน resize/augment มาแล้ว (ขนาดสุดท้าย)
            spec = tuple ชื่อช่อง 3 ตัว เช่น ("gray", "clahe", "mask")
    output: array รูปร่าง (H, W, 3) ค่า 0.0-1.0 พร้อมส่งต่อไป normalize

    เรียงตามสูตรเป๊ะ ห้ามสลับลำดับหลังเทรนโมเดลไปแล้ว เพราะ weight ของชั้นแรก
    ผูกกับความหมายของแต่ละช่อง สลับทีหลัง = โมเดลอ่านผิดช่องทั้งหมด
    """
    if len(spec) != 3:
        raise ValueError(f"สูตรช่องสีต้องมี 3 ช่องพอดี ได้รับ {len(spec)}: {spec}")

    chans = []
    for name in spec:
        fn = CHANNEL_BUILDERS.get(name)
        if fn is None:
            valid = ", ".join(sorted(CHANNEL_BUILDERS))
            raise ValueError(f"ไม่รู้จักช่อง '{name}' — ต้องเป็นหนึ่งใน: {valid}")
        chans.append(fn(img))

    return np.stack(chans, axis=-1)


def warn_if_mask_unusable(spec, variant: str):
    """
    เตือนถ้าใช้ช่อง mask กับ variant ที่ไม่มีพื้นหลังดำ (เช่น xray_bbox)

    ไม่ raise เพราะไม่ใช่ความผิดพลาดร้ายแรง (โมเดลยังเทรนได้ แค่ช่องนั้นไร้ค่า)
    แต่ต้องเตือน ไม่งั้นจะเสียเวลาเทรนแล้วสงสัยทีหลังว่าทำไมไม่ต่างจากเดิมเลย
    """
    if "mask" in spec and variant not in MASK_CHANNEL_VARIANTS:
        print(f"  เตือน: สูตรช่องสีมีช่อง mask แต่ variant = '{variant}' ซึ่งไม่มีพื้นหลังดำ "
              f"-> ช่องนั้นจะเป็น 1 เกือบทั้งภาพ ไม่ให้ข้อมูลอะไร "
              f"(ช่อง mask ใช้ได้กับ {sorted(MASK_CHANNEL_VARIANTS)} เท่านั้น)")
