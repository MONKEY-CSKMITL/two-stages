def get_preprocess_fn(name):
    """
    แปลง "ชื่อจาก config" เป็น "ฟังก์ชันจริง" ให้ train.py / gradcam.py เอาไปใช้

    input:  name = ชื่อจาก config (data.preprocess) หรือ None ถ้าไม่ได้ระบุ
    output: ฟังก์ชันที่รับ PIL คืน PIL — หรือ None ถ้าไม่ต้องแต่งภาพเลย

    ไม่ระบุมา (None) = ไม่แต่งภาพ ซึ่งเป็นพฤติกรรมเดิมของทุก config ที่มีอยู่แล้ว
    จึงไม่ต้องแก้ config เก่าสักไฟล์ ผลการทดลองเดิมยังรันซ้ำได้เหมือนเดิมทุกประการ
    """
    if name is None:
        return None

    key = str(name).strip().lower()
    if key not in PREPROCESS_FNS:
        valid = ", ".join(sorted(PREPROCESS_FNS))
        raise ValueError(
            f"data.preprocess = '{name}' ไม่รู้จัก — ต้องเป็นหนึ่งใน: {valid}\n"
            f"(ถ้าเพิ่งเขียนฟังก์ชันใหม่ อย่าลืมลงทะเบียนใน PREPROCESS_FNS ที่ preprocessing.py)"
        )
    return PREPROCESS_FNS[key]