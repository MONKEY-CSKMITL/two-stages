"""
preprocessing.py — ที่เก็บฟังก์ชันแต่งภาพเพิ่มเติม (สำหรับทำ ablation ทีหลัง)

ทุกฟังก์ชันในไฟล์นี้มีรูปแบบเดียวกัน: รับภาพ PIL 1 ใบ คืนภาพ PIL 1 ใบกลับมา
เอาไปส่งให้ prepare_image(..., preprocess_fn=ฟังก์ชันในไฟล์นี้) ได้ทันที

เลือกใช้จาก config ด้วยชื่อ (data.preprocess: no_preprocess) — train.py กับ
gradcam.py จะเรียก get_preprocess_fn() แปลงชื่อเป็นฟังก์ชันให้เอง

ข้อควรรู้: ฟังก์ชันในไฟล์นี้ใช้กับทั้ง 3 ชุด (train/val/test) เหมือนกันหมด และ
ต้องให้ผลเดิมทุกครั้งที่เรียกด้วยภาพเดียวกัน (deterministic) — ไม่ใช่ที่สำหรับ
augmentation ที่ต้องสุ่มและต้องทำเฉพาะชุด train

--------------------------------------------------------------------------
กติกาเรื่อง "พื้นหลัง" ที่ทุกฟังก์ชันในไฟล์นี้ยึดร่วมกัน
--------------------------------------------------------------------------
crop แบบ xray_masked มีพื้นหลังเป็น 0 สนิท และกินพื้นที่ราว 23% ของกรอบ
(วัดจาก manifest: พิกเซลกระดูกเฉลี่ย 77% ของ bbox) ถ้าเอาพื้นดำก้อนนี้ไปคิด
รวมในสถิติของภาพ ค่าที่ได้จะเพี้ยนหมด — histogram จะมีแท่งยักษ์ที่ 0,
percentile เลื่อน, ค่าเฉลี่ยต่ำเกินจริง ฉะนั้นทุกฟังก์ชันที่นี่ยึดกติกา 3 ข้อ:

  1. คิดสถิติจาก "พิกเซลกระดูก" เท่านั้น = พิกเซลที่ค่ามากกว่า 0
  2. หลังแต่งภาพเสร็จ ทาพื้นหลังกลับเป็น 0 เสมอ (กันการแต่งภาพไปสร้าง
     ขอบเทียมหรือ noise ในพื้นที่ที่ควรว่างเปล่า)
  3. พิกเซลกระดูกต้องไม่มีค่าเป็น 0 หลังแต่งภาพ (บีบไปอยู่ที่ 1-255 แทน)
     — ข้อนี้สำคัญตอนต่อฟังก์ชันหลายตัวเข้าด้วยกัน ถ้าปล่อยให้พิกเซลกระดูก
     กลายเป็น 0 ฟังก์ชันตัวถัดไปจะเข้าใจผิดว่ามันเป็นพื้นหลัง

กติกานี้ใช้กับ crop แบบ xray_bbox ได้เหมือนกันโดยไม่ต้องแยกเงื่อนไข เพราะภาพ
bbox แทบไม่มีพิกเซลที่เป็น 0 พอดี เงื่อนไข "> 0" จึงกินทั้งภาพอยู่แล้ว
"""

import numpy as np
from PIL import Image

# ค่าที่ถือว่าเป็นพื้นหลังของ crop แบบ masked (crop.py เขียน 0 ลงไปตรงๆ)
BACKGROUND_VALUE = 0


def _split_gray(img: Image.Image):
    """
    แยกภาพ PIL ออกเป็น (ตารางตัวเลขขาวดำ, โหมดเดิม) เพื่อให้ฟังก์ชันแต่งภาพ
    ทำงานกับตัวเลขได้สะดวก แล้วประกอบกลับเป็น PIL โหมดเดิมทีหลัง

    ต้องรองรับ 2 โหมด เพราะ transforms.py เรียก preprocess_fn คนละจุดกัน:
      - เส้นทางทั่วไป (EfficientNet/ConvNeXt) ส่งภาพโหมด "L" (ขาวดำช่องเดียว) มา
      - เส้นทาง RAD-DINO ส่งภาพโหมด "RGB" มา (ตาม do_convert_rgb ใน config ทางการ)
    ภาพต้นทางเป็น X-ray ขาวดำอยู่แล้ว การแปลง RGB -> L -> RGB จึงไม่เสียข้อมูล
    """
    if img.mode == "L":
        return np.array(img), "L"
    return np.array(img.convert("L")), img.mode


def _merge_gray(gray: np.ndarray, mode: str) -> Image.Image:
    """ประกอบตารางตัวเลขกลับเป็นภาพ PIL โหมดเดิม (คู่กับ _split_gray)"""
    out = Image.fromarray(gray.astype(np.uint8), mode="L")
    return out if mode == "L" else out.convert(mode)


def no_preprocess(img: Image.Image) -> Image.Image:
    """
    ฟังก์ชันว่าง — ไม่ทำอะไรกับภาพเลย แค่คืนกลับไปเหมือนเดิม

    มีไว้เพื่อทดสอบว่า "เส้นทางที่มี preprocess_fn" ทำงานถูกต้อง โดยที่ผลลัพธ์
    ต้องเหมือนกับตอนที่ preprocess_fn=None เป๊ะ (เพราะฟังก์ชันนี้ไม่แก้อะไรเลย)
    ถ้าทดสอบแล้วผลไม่เหมือนกัน แปลว่าโค้ดจุดเสียบปลั๊กมีปัญหา
    """
    return img   # คืนภาพเดิม ไม่แตะต้องอะไรเลย


def normalize(img: Image.Image, lo_pct: float = 1.0, hi_pct: float = 99.0) -> Image.Image:
    """
    ปรับความสว่าง/คอนทราสต์ของภาพให้อยู่ในสเกลเดียวกันทุกใบ (per-image normalization)

    ปัญหาที่แก้: ภาพ DXA ของคนไข้แต่ละคนถ่ายมาด้วยความสว่างไม่เท่ากัน (ขึ้นกับ
    ความหนาของตัวคนไข้ การตั้งค่าเครื่อง ฯลฯ) ท่อเดิมทำแค่หารด้วย 255 แล้วลบค่า
    เฉลี่ยของ ImageNet ซึ่งเป็นค่าคงที่ก้อนเดียวใช้กับทุกภาพ จึงไม่ได้ชดเชยความ
    ต่างระหว่างคนไข้เลย โมเดลต้องเสียกำลังส่วนหนึ่งไปเรียนรู้ที่จะ "มองข้าม"
    ความสว่างที่ไม่เกี่ยวกับโรค

    วิธีทำ: หาค่าที่ percentile 1 กับ 99 ของ "พิกเซลกระดูก" แล้วยืดช่วงนั้นให้
    เต็มสเกล ใช้ percentile แทนค่า min/max เพราะ min/max อ่อนไหวกับพิกเซลหลุด
    เพียงจุดเดียว (จุดขาวจ้าจุดเดียวจะบีบทั้งภาพให้มืดลงหมด) การตัดหัวท้าย 1%
    ทิ้งจึงทนต่อสิ่งแปลกปลอมได้ดีกว่ามาก

    ผลข้างเคียงที่ตั้งใจ: พิกเซลที่สว่างเกิน hi_pct หรือมืดกว่า lo_pct จะถูกตัด
    (clip) ให้เท่ากันหมด = เสียรายละเอียดที่ปลายสองข้างไป 2% แลกกับการที่
    รายละเอียด 98% ตรงกลาง (ซึ่งคือเนื้อกระดูก) ได้ใช้สเกลเต็มความละเอียด
    """
    gray, mode = _split_gray(img)
    bone = gray > BACKGROUND_VALUE

    if not bone.any():           # ภาพดำสนิททั้งใบ (ไม่ควรเกิด แต่กันไว้)
        return img               # ไม่มีอะไรให้คำนวณ คืนภาพเดิม

    bone_values = gray[bone]     # เอาเฉพาะค่าความสว่างของพิกเซลกระดูกมาคิด (กติกาข้อ 1)
    lo = float(np.percentile(bone_values, lo_pct))
    hi = float(np.percentile(bone_values, hi_pct))
    if hi <= lo:                 # กระดูกมีค่าความสว่างเดียวทั้งก้อน หารด้วย 0 ไม่ได้
        return img

    # ยืดช่วง [lo, hi] -> [0, 1] แล้วตัดส่วนที่ล้นออกนอกช่วงทิ้ง
    out = (gray.astype(np.float32) - lo) / (hi - lo)
    out = np.clip(out, 0.0, 1.0)

    # แปลงกลับเป็น 0-255 แต่บีบพิกเซลกระดูกไว้ที่ 1-255 (ไม่ให้แตะ 0)
    # ตามกติกาข้อ 3 ที่หัวไฟล์ — ถ้าปล่อยให้พิกเซลกระดูกที่มืดที่สุดกลายเป็น 0
    # ฟังก์ชันตัวถัดไปในสายจะนับมันเป็นพื้นหลัง ทำให้รูปทรงกระดูกแหว่ง
    out = 1.0 + out * 254.0
    out[~bone] = BACKGROUND_VALUE     # ทาพื้นหลังกลับเป็น 0 ตามกติกาข้อ 2

    return _merge_gray(out, mode)


def clahe(img: Image.Image, clip_limit: float = 2.0, tile_grid: int = 8) -> Image.Image:
    """
    เพิ่มความคมชัดเฉพาะจุด (Contrast Limited Adaptive Histogram Equalization)
    ตามที่รุ่นพี่รายงานว่าช่วยดันคลาส "เล็กน้อย" จาก 0% เป็น 47.5%

    ทำไมถึงน่าจะช่วยกับโจทย์นี้โดยเฉพาะ: เกณฑ์ Genant ตัดสินจากสัดส่วนความสูงที่
    ขอบหน้า-กลาง-หลังของปล้อง ซึ่งต้องมองเห็น "เส้น endplate" (ขอบบน-ล่างของ
    กระดูก) ให้ชัด CLAHE ปรับคอนทราสต์แยกเป็นช่องเล็กๆ ทั่วภาพ จึงดันคอนทราสต์
    ตรงขอบที่จางให้เด่นขึ้นได้ โดยไม่ทำให้ส่วนที่สว่างอยู่แล้วสว่างจนไหม้

    clip_limit = เพดานกันการขยายคอนทราสต์เกินพอดี (ยิ่งสูงยิ่งแรงและยิ่งดัน noise)
                 2.0 เป็นค่ามาตรฐานที่ใช้กันทั่วไป
    tile_grid  = แบ่งภาพเป็นกี่ช่องต่อด้าน (8 = 8x8 = 64 ช่อง) crop ของเรามีขนาด
                 กลางๆ ราว 127x93 px ฉะนั้น 1 ช่องจะราว 16x12 px

    ⚠️ จุดที่ต้องระวังกับ crop แบบ masked: ช่องที่ตกอยู่ตรงมุมภาพจะมีพื้นดำเกือบ
    เต็มช่อง histogram ของช่องนั้นจึงมีแต่ค่า 0 CLAHE จะพยายามยืดคอนทราสต์ของ
    พิกเซลกระดูกไม่กี่จุดที่เหลือจนเกินจริง เราจึงทาพื้นหลังกลับเป็น 0 ทีหลังเสมอ
    (กติกาข้อ 2) ซึ่งลบ artifact ในพื้นที่ว่างออกได้ แต่**ไม่ได้แก้**พิกเซลกระดูก
    ริมขอบที่โดนขยายเกินจริงไปแล้ว — ข้อจำกัดนี้เป็นสิ่งที่การทดลองต้องวัดว่าคุ้มไหม
    """
    try:
        import cv2
    except ImportError as e:
        raise ImportError("preprocess='clahe' ต้องติดตั้ง opencv ก่อน: pip install opencv-python") from e

    gray, mode = _split_gray(img)
    bone = gray > BACKGROUND_VALUE

    if not bone.any():
        return img

    op = cv2.createCLAHE(clipLimit=clip_limit, tileGridSize=(tile_grid, tile_grid))
    out = op.apply(gray)

    out = np.maximum(out, 1)          # กติกาข้อ 3: พิกเซลกระดูกห้ามเป็น 0
    out[~bone] = BACKGROUND_VALUE     # กติกาข้อ 2: พื้นหลังกลับไปเป็น 0

    return _merge_gray(out, mode)


def normalize_clahe(img: Image.Image) -> Image.Image:
    """
    ต่อ 2 ขั้นเข้าด้วยกัน: ปรับสเกลความสว่างก่อน แล้วค่อยเพิ่มคอนทราสต์เฉพาะจุด

    ทำไมเรียงลำดับนี้: CLAHE ตัดสินความแรงจาก histogram ของแต่ละช่อง ถ้าภาพเข้า
    มาด้วยสเกลความสว่างที่ต่างกันคนละแบบ ความแรงที่ CLAHE ใส่ลงไปก็จะต่างกันไป
    ด้วยโดยไม่ตั้งใจ การ normalize ก่อนทำให้ทุกภาพเข้า CLAHE ด้วยสเกลเดียวกัน
    ผลที่ได้จึงสม่ำเสมอกว่าและอธิบายได้ง่ายกว่า

    มีไว้เพื่อตอบว่า "ผลของ 2 ตัวรวมกัน มากกว่าผลของตัวใดตัวหนึ่งเดี่ยวๆ ไหม"
    ซึ่งตอบไม่ได้ถ้ารันแค่ตัวเดี่ยว 2 การทดลอง
    """
    return clahe(normalize(img))


def destripe(img: Image.Image, window: int = 5, min_bone_px: int = 10,
             max_shift: float = 25.0) -> Image.Image:
    """
    ลบ "ลายเส้นแนวนอน" ที่ติดมากับการสแกนของเครื่อง DXA

    --- artifact ตัวนี้คืออะไร ---
    เครื่อง DXA สแกนภาพทีละแถวจากบนลงล่าง แต่ละแถวจึงมี gain/offset ต่างกัน
    เล็กน้อย ผลคือภาพมีลายเส้นแนวนอนจางๆ ซ้อนอยู่ทั่วทั้งใบ มองแทบไม่เห็นในภาพดิบ
    เพราะคอนทราสต์ต่ำ แต่จะเด่นขึ้นทันทีเมื่อผ่าน CLAHE (วัดได้ว่าแรงขึ้น 17%)

    --- ทำไมต้องระวังเป็นพิเศษกับโจทย์นี้ ---
    วิธีลบลายเส้นที่นิยมใช้กันคือ FFT notch filter ตัดความถี่ในแนวตั้งทิ้ง
    **ใช้กับงานนี้ไม่ได้** เพราะ "เส้น endplate" (ขอบบน-ล่างของกระดูก) ก็เป็น
    โครงสร้างแนวนอนเหมือนกัน การตัดความถี่แนวตั้งจะลบสิ่งที่เราต้องการวัดที่สุด
    ทิ้งไปพร้อมกับ noise

    --- วิธีที่ใช้แทน ---
    ลบเฉพาะ "ค่าคงที่ที่เลื่อนไปทั้งแถว" ไม่ใช่ลบโครงสร้างแนวนอนทั้งหมด:
      1. หาค่าเฉลี่ยความสว่างของพิกเซลกระดูกในแต่ละแถว -> ได้เส้นโปรไฟล์แนวตั้ง
      2. ทำ median filter บนเส้นโปรไฟล์นั้น (หน้าต่างแคบๆ)
      3. ส่วนต่างระหว่างของจริงกับที่ผ่าน median = การเลื่อนของแถวนั้น -> ลบทิ้ง

    ใช้ median ไม่ใช่ค่าเฉลี่ยเคลื่อนที่ เพราะ median รักษา "ขอบแบบขั้นบันได" ไว้ได้
    ขณะที่ลบค่าโดดของแถวเดี่ยวๆ ออก — ตรงกับสิ่งที่ต้องการพอดี คือ endplate ซึ่ง
    เป็นการเปลี่ยนความสว่างแบบขั้นบันไดจะรอด ส่วนการกระตุกทีละแถวจะถูกลบ

    window      = ความกว้างหน้าต่าง median (แถว) — แคบไว้เพื่อไม่ไปแตะโครงสร้างจริง
    min_bone_px = แถวที่มีพิกเซลกระดูกน้อยกว่านี้ไม่แก้ (ค่าเฉลี่ยไม่น่าเชื่อถือ
                  มักเป็นแถวบนสุด/ล่างสุดที่เฉียดขอบกระดูก)
    max_shift   = จำกัดขนาดการแก้ต่อแถว กันกรณีคำนวณเพี้ยนแล้วไปทำภาพพัง
    """
    gray, mode = _split_gray(img)
    bone = gray > BACKGROUND_VALUE

    if not bone.any():
        return img

    arr = gray.astype(np.float32)

    # --- ขั้นที่ 1: โปรไฟล์ความสว่างเฉลี่ยรายแถว (คิดเฉพาะพิกเซลกระดูก) ---
    counts = bone.sum(axis=1)
    sums = np.where(bone, arr, 0.0).sum(axis=1)
    valid = counts >= min_bone_px
    if valid.sum() < window:      # กระดูกบางเกินไป ไม่มีข้อมูลพอให้ประมาณ
        return img

    profile = np.zeros(arr.shape[0], dtype=np.float32)
    profile[valid] = sums[valid] / counts[valid]

    # --- ขั้นที่ 2: median filter บนโปรไฟล์ (เฉพาะแถวที่ใช้ได้) ---
    idx = np.flatnonzero(valid)
    vals = profile[idx]
    half = window // 2
    padded = np.pad(vals, half, mode="edge")
    smooth = np.array([np.median(padded[i:i + window]) for i in range(len(vals))],
                      dtype=np.float32)

    # --- ขั้นที่ 3: ลบส่วนต่างออกจากทุกพิกเซลกระดูกในแถวนั้น ---
    shift = np.clip(vals - smooth, -max_shift, max_shift)
    correction = np.zeros(arr.shape[0], dtype=np.float32)
    correction[idx] = shift

    out = arr - correction[:, None]

    out = np.clip(out, 1, 255)            # กติกา 3: พิกเซลกระดูกอยู่ในช่วง 1-255
    out[~bone] = BACKGROUND_VALUE          # กติกา 2: พื้นหลังกลับไปเป็น 0

    return _merge_gray(out, mode)


def destripe_clahe(img: Image.Image) -> Image.Image:
    """
    ลบลายเส้นก่อน แล้วค่อยเพิ่มคอนทราสต์เฉพาะจุด

    ลำดับนี้สำคัญและเป็นเหตุผลทั้งหมดที่เขียน destripe ขึ้นมา: CLAHE ขยายทุกอย่าง
    ที่มีความเปรียบต่างในบริเวณเล็กๆ รวมถึงลายเส้นด้วย (วัดได้ว่า +17%) ถ้าลบลายเส้น
    ออกไปก่อน CLAHE จะเหลือแต่โครงสร้างจริงให้ขยาย

    การทดลองก่อนหน้าพบว่า CLAHE เดี่ยวๆ ทำให้ recall ของ mild แย่ลง (0.543 -> 0.478)
    สมมติฐานคือ noise ที่ถูกขยายไปกลบสัญญาณบางๆ ของ mild — ถ้าสมมติฐานถูก
    ชุดนี้ควรได้ mild กลับมาพร้อมกับ moderate ที่ CLAHE ช่วยอยู่แล้ว
    """
    return clahe(destripe(img))


def _masked_blur(arr: np.ndarray, bone: np.ndarray, sigma: float) -> np.ndarray:
    """
    เบลอภาพโดย "ไม่ให้พื้นหลังดำดูดค่า" (normalized convolution)

    ทำไมเบลอตรงๆ ไม่ได้: crop แบบ masked มีพื้นหลังเป็น 0 กินพื้นที่ 23% พอเบลอ
    ปกติ ค่า 0 จะไหลเข้ามาผสมกับเนื้อกระดูกที่อยู่ริมขอบ ทำให้ค่าเฉลี่ยแถวขอบต่ำ
    เกินจริง เวลาเอาไปลบออกจะเกิด "ขอบเรืองแสง" (halo) รอบกระดูกทั้งใบ ซึ่งเป็น
    สัญญาณปลอมที่อยู่ตรงตำแหน่งเดียวกับ endplate ที่เราต้องใช้วัดพอดี

    วิธีแก้: เบลอทั้ง "ภาพที่คูณ mask" และ "ตัว mask" แล้วหารกัน
      - ตัวเศษ = ผลรวมความสว่างของพิกเซลกระดูกในละแวกนั้น
      - ตัวส่วน = จำนวนพิกเซลกระดูกในละแวกเดียวกัน
    ได้ค่าเฉลี่ยเฉพาะพิกเซลกระดูกจริงๆ พื้นหลังไม่มีส่วนร่วมเลย
    """
    from scipy.ndimage import gaussian_filter

    num = gaussian_filter(np.where(bone, arr, 0.0).astype(np.float32), sigma, mode="nearest")
    den = gaussian_filter(bone.astype(np.float32), sigma, mode="nearest")
    return np.where(den > 1e-6, num / np.maximum(den, 1e-6), 0.0)


def unsharp(img: Image.Image, sigma: float = 3.0, amount: float = 1.0) -> Image.Image:
    """
    เน้นรายละเอียดขอบให้คมขึ้น (unsharp mask)

    สูตร: ภาพใหม่ = ภาพเดิม + amount x (ภาพเดิม - ภาพเบลอ)
    ส่วน (ภาพเดิม - ภาพเบลอ) คือ "รายละเอียดที่หายไปตอนเบลอ" = ขอบและลวดลาย
    การบวกกลับเข้าไปจึงเป็นการเน้นสิ่งเหล่านั้นให้เด่นขึ้น

    ทำไมน่าจะช่วย mild โดยเฉพาะ: Genant grade 1 คือความสูงลดเพียง 20-25% ซึ่งอยู่
    ในช่วงความแปรผันตามธรรมชาติของกระดูกปกติ การจะแยกออกได้ต้องเห็น "เส้น endplate"
    (ขอบบน-ล่างของกระดูก) ชัดพอที่จะเห็นว่ามันเว้าหรือยุบ — ต่างจาก moderate/severe
    ที่รูปทรงโดยรวมเปลี่ยนจนดูออกโดยไม่ต้องเพ่งขอบ

    ต่างจาก CLAHE อย่างไร: CLAHE ปรับ histogram แยกทีละช่องสี่เหลี่ยม จึงขยาย
    ทุกอย่างในช่องที่มีความเปรียบต่างต่ำ รวมถึง noise (วัดได้ว่าขยายลายเส้น +17%)
    ส่วน unsharp ทำงานตามขนาดของโครงสร้าง (คุมด้วย sigma) จึงเลือกเน้นเฉพาะ
    รายละเอียดขนาดที่เราสนใจได้ ไม่เหวี่ยงแหเหมือน CLAHE

    sigma  = ขนาดโครงสร้างที่จะถูกนับเป็น "รายละเอียด" (3 px เหมาะกับความหนาของ
             เปลือกกระดูกที่ขอบ endplate ในภาพขนาด ~127x93 px ของเรา)
    amount = ความแรง (1.0 = เพิ่มรายละเอียดกลับเข้าไปเท่าตัว)
    """
    gray, mode = _split_gray(img)
    bone = gray > BACKGROUND_VALUE
    if not bone.any():
        return img

    arr = gray.astype(np.float32)
    blur = _masked_blur(arr, bone, sigma)
    out = arr + amount * (arr - blur)

    out = np.clip(out, 1, 255)
    out[~bone] = BACKGROUND_VALUE
    return _merge_gray(out, mode)


def flatten(img: Image.Image, sigma: float = 25.0) -> Image.Image:
    """
    ลบการไล่แสงช้าๆ ทั่วปล้องออก เหลือแต่โครงสร้าง (high-pass / homomorphic)

    สูตร: ภาพใหม่ = ภาพเดิม - ภาพเบลอมาก + ค่ากลาง
    ภาพที่เบลอด้วย sigma ใหญ่ = "แสงพื้นหลัง" ที่ค่อยๆ ไล่จากด้านหนึ่งไปอีกด้าน
    ซึ่งมาจากความหนาของตัวคนไข้และมุมของลำรังสี ไม่ใช่พยาธิสภาพ

    ต่างจาก normalize() ที่ทำไปแล้ว: normalize แก้ความต่าง "ระหว่างภาพ" (ภาพนี้
    สว่างกว่าภาพนั้น) ด้วยการแปลงเชิงเส้นทั้งใบ แต่แก้ความต่าง "ภายในภาพเดียวกัน"
    (มุมซ้ายบนสว่างกว่ามุมขวาล่าง) ไม่ได้เลย — ซึ่งเป็นสิ่งที่ฟังก์ชันนี้แก้

    sigma = ขนาดของ "แสงพื้นหลัง" ที่จะลบทิ้ง (25 px = ราว 1/5 ของความกว้างปล้อง
            ใหญ่พอที่จะไม่ไปลบตัวกระดูกเอง แต่เล็กพอจะจับการไล่แสงได้)
    """
    gray, mode = _split_gray(img)
    bone = gray > BACKGROUND_VALUE
    if not bone.any():
        return img

    arr = gray.astype(np.float32)
    blur = _masked_blur(arr, bone, sigma)
    center = float(arr[bone].mean())      # ดึงกลับมาไว้ที่ความสว่างเดิมของภาพ
    out = arr - blur + center

    out = np.clip(out, 1, 255)
    out[~bone] = BACKGROUND_VALUE
    return _merge_gray(out, mode)


def destripe_unsharp(img: Image.Image) -> Image.Image:
    """
    ลบลายเส้นก่อน แล้วค่อยเน้นขอบ — ต่อยอดจากชุดที่ได้ผลดีที่สุดตอนนี้

    ลำดับสำคัญ: unsharp เน้น "ทุกอย่างที่เป็นรายละเอียดขนาดเล็ก" ซึ่งลายเส้นแนวนอน
    ก็เข้าข่าย ถ้าไม่ลบก่อนจะเจอปัญหาเดียวกับที่ CLAHE เจอ (ขยาย noise แล้วกลบ
    สัญญาณของ mild) — destripe ลดการกระตุกรายแถวไปแล้ว 71% จึงเหลือแต่ของจริงให้เน้น
    """
    return unsharp(destripe(img))


def destripe_flatten(img: Image.Image) -> Image.Image:
    """ลบลายเส้น แล้วลบแสงพื้นหลัง — คู่เทียบของ destripe_unsharp"""
    return flatten(destripe(img))


